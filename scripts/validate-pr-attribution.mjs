#!/usr/bin/env node
// Deterministic PR-body attribution validator.
//
// Enforces the Git Delivery attribution contract in AGENTS.md: every PR body
// must contain exactly one occurrence of the repository-standard attribution
// line, and must not carry a provider-default "Generated with ..." footer.

import { readFileSync } from 'node:fs';

export const REQUIRED_ATTRIBUTION_LINE = 'Generated by Claude, GPT, and Mike.';
const PROVIDER_DEFAULT_PREFIX = '🤖 Generated with';

/**
 * Validates a PR body against the repository's attribution contract.
 *
 * @param {string | null | undefined} body
 * @returns {{ valid: boolean, errors: string[] }}
 */
export function validatePrAttribution(body) {
  const lines = (body ?? '').split(/\r?\n/).map((line) => line.trim());

  const requiredLineCount = lines.filter((line) => line === REQUIRED_ATTRIBUTION_LINE).length;
  const providerDefaultLines = lines.filter((line) => line.startsWith(PROVIDER_DEFAULT_PREFIX));

  const errors = [];

  if (requiredLineCount === 0) {
    errors.push(`Missing required attribution line: "${REQUIRED_ATTRIBUTION_LINE}"`);
  } else if (requiredLineCount > 1) {
    errors.push(
      `Required attribution line must appear exactly once, found ${requiredLineCount} occurrences.`,
    );
  }

  if (providerDefaultLines.length > 0) {
    errors.push(
      'Provider-default attribution is not allowed and must be removed (replaced by the ' +
        `repository-standard line): ${providerDefaultLines.map((line) => JSON.stringify(line)).join(', ')}`,
    );
  }

  return { valid: errors.length === 0, errors };
}

function readPrBodyFromGithubEvent() {
  const eventPath = process.env.GITHUB_EVENT_PATH;
  if (!eventPath) {
    return undefined;
  }
  const event = JSON.parse(readFileSync(eventPath, 'utf8'));
  const body = event.pull_request?.body;
  return typeof body === 'string' ? body : undefined;
}

function resolveBody(argv) {
  const [flag, value] = argv;
  if (flag === '--body-file' && value) {
    return readFileSync(value, 'utf8');
  }
  if (flag === '--body' && value !== undefined) {
    return value;
  }
  return readPrBodyFromGithubEvent();
}

function main() {
  const body = resolveBody(process.argv.slice(2));

  if (body === undefined) {
    console.error(
      'validate-pr-attribution: no PR body found. Provide one via GITHUB_EVENT_PATH ' +
        '(pull_request.body), --body-file <path>, or --body <string>.',
    );
    process.exitCode = 1;
    return;
  }

  const result = validatePrAttribution(body);

  if (!result.valid) {
    console.error('PR attribution validation failed:');
    for (const error of result.errors) {
      console.error(`  - ${error}`);
    }
    process.exitCode = 1;
    return;
  }

  console.log('PR attribution validation passed.');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  main();
}
